-- 1. TABLA DE ROLES
CREATE TABLE ROLES (
  ID_ROL NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE_ROL VARCHAR2(50) NOT NULL,
  DESCRIPCION VARCHAR2(200),
  CONSTRAINT PK_ROLES PRIMARY KEY (ID_ROL),
  CONSTRAINT UK_ROLES_NOMBRE UNIQUE (NOMBRE_ROL)
);

-- 2. TABLA DE USUARIOS DEL PANEL
CREATE TABLE USUARIOS (
  ID_USUARIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_ROL NUMBER NOT NULL,
  USERNAME VARCHAR2(50) NOT NULL,
  EMAIL VARCHAR2(100) NOT NULL,
  NOMBRE_COMPLETO VARCHAR2(150) NOT NULL,
  CLAVE_HASH VARCHAR2(256),
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
  CONSTRAINT FK_USUARIOS_ROL FOREIGN KEY (ID_ROL) REFERENCES ROLES(ID_ROL),
  CONSTRAINT UK_USUARIOS_USER UNIQUE (USERNAME),
  CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
  CONSTRAINT CK_USUARIOS_ACTIVO CHECK (ACTIVO IN ('S','N'))
);

-- 3. TABLA DE CATEGORÍAS (Consolas Next-Gen, Laptops Gamer, Retro Restoration, etc.)
CREATE TABLE CATEGORIAS (
  ID_CATEGORIA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(100) NOT NULL,
  DESCRIPCION VARCHAR2(300),
  GARANTIA_MESES_DEFECTO NUMBER(2) DEFAULT 12 NOT NULL,
  SLUG VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_CATEGORIAS PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UK_CATEGORIAS_SLUG UNIQUE (SLUG)
);

-- 4. TABLA DE PROVEEDORES
CREATE TABLE PROVEEDORES (
  ID_PROVEEDOR NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(150) NOT NULL,
  TIPO_PROVEEDOR VARCHAR2(20) DEFAULT 'PARTICULAR' NOT NULL,
  TELEFONO VARCHAR2(30),
  EMAIL VARCHAR2(100),
  DIRECCION VARCHAR2(250),
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_PROVEEDORES PRIMARY KEY (ID_PROVEEDOR),
  CONSTRAINT CK_PROVEEDORES_TIPO CHECK (TIPO_PROVEEDOR IN ('EMPRESA','PARTICULAR'))
);

-- 5. TABLA DE CLIENTES
CREATE TABLE CLIENTES (
  ID_CLIENTE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(150) NOT NULL,
  TELEFONO VARCHAR2(30),
  EMAIL VARCHAR2(100),
  DIRECCION VARCHAR2(250),
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE)
);

-- 6. TABLA DE PRODUCTOS (Consolas, Laptops, Retro y Accesorios)
CREATE TABLE PRODUCTOS (
  ID_PRODUCTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_CATEGORIA NUMBER NOT NULL,
  ID_PROVEEDOR NUMBER,
  SKU VARCHAR2(50),
  NOMBRE VARCHAR2(150) NOT NULL,
  MARCA VARCHAR2(80) NOT NULL,
  MODELO VARCHAR2(80) NOT NULL,
  TIPO_HARDWARE VARCHAR2(20) DEFAULT 'NEXT_GEN' NOT NULL, -- NEXT_GEN, LAPTOP, RETRO, ACCESORIO
  PRECIO_VENTA NUMBER(10,2) NOT NULL,
  PRECIO_COMPRA NUMBER(10,2) DEFAULT 0 NOT NULL,
  STOCK NUMBER(6) DEFAULT 0 NOT NULL,
  DESCRIPCION CLOB,
  FECHA_INGRESO DATE DEFAULT SYSDATE NOT NULL,
  ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_PRODUCTOS PRIMARY KEY (ID_PRODUCTO),
  CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIAS(ID_CATEGORIA),
  CONSTRAINT FK_PRODUCTO_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR) REFERENCES PROVEEDORES(ID_PROVEEDOR),
  CONSTRAINT CK_PRODUCTO_TIPO CHECK (TIPO_HARDWARE IN ('NEXT_GEN','LAPTOP','RETRO','ACCESORIO')),
  CONSTRAINT CK_PRODUCTO_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CONSTRAINT CK_PRODUCTO_STOCK CHECK (STOCK >= 0),
  CONSTRAINT CK_PRODUCTO_PRECIO CHECK (PRECIO_VENTA >= 0)
);

-- 7. TABLA DE CERTIFICADOS DE INSPECCIÓN TÉCNICA #GS
CREATE TABLE CERTIFICADOS_GS (
  ID_CERTIFICADO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_PRODUCTO NUMBER NOT NULL,
  CODIGO_CERTIFICADO VARCHAR2(30) NOT NULL, -- Ej. #GS-2201, #GS-2202
  HARDWARE_ORIGINAL_PCT NUMBER(3) DEFAULT 100 NOT NULL,
  ESTADO_ESTETICO_PCT NUMBER(3) DEFAULT 95 NOT NULL,
  RENDIMIENTO_TERMICO_PCT NUMBER(3) DEFAULT 98 NOT NULL,
  PUNTOS_REVISADOS NUMBER(3) DEFAULT 30 NOT NULL,
  MESES_GARANTIA NUMBER(2) DEFAULT 12 NOT NULL,
  DETALLE_INSPECCION CLOB,
  FECHA_INSPECCION DATE DEFAULT SYSDATE NOT NULL,
  TECNICO_RESPONSABLE VARCHAR2(100) DEFAULT 'Laboratorio Gaming Solutions' NOT NULL,
  CONSTRAINT PK_CERTIFICADOS_GS PRIMARY KEY (ID_CERTIFICADO),
  CONSTRAINT FK_CERT_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS(ID_PRODUCTO) ON DELETE CASCADE,
  CONSTRAINT UK_CERT_CODIGO UNIQUE (CODIGO_CERTIFICADO),
  CONSTRAINT CK_CERT_HW CHECK (HARDWARE_ORIGINAL_PCT BETWEEN 0 AND 100),
  CONSTRAINT CK_CERT_ESTETICO CHECK (ESTADO_ESTETICO_PCT BETWEEN 0 AND 100),
  CONSTRAINT CK_CERT_TERMICO CHECK (RENDIMIENTO_TERMICO_PCT BETWEEN 0 AND 100)
);

-- 8. ESPECIFICACIÓN DETALLADA PARA RETRO RESTORATION
CREATE TABLE PRODUCTOS_DETALLE_RETRO (
  ID_PRODUCTO NUMBER NOT NULL,
  CONDICION_ESTETICA_10 NUMBER(2) DEFAULT 8 NOT NULL,
  INCLUYE_CAJA CHAR(1) DEFAULT 'N' NOT NULL,
  INCLUYE_MANUAL CHAR(1) DEFAULT 'N' NOT NULL,
  ESTADO_FUNCIONAL VARCHAR2(30) DEFAULT 'RESTAURO_TOTAL' NOT NULL,
  RECAP_REALIZADO CHAR(1) DEFAULT 'S' NOT NULL,
  OBSERVACIONES VARCHAR2(1000),
  CONSTRAINT PK_DETALLE_RETRO PRIMARY KEY (ID_PRODUCTO),
  CONSTRAINT FK_RETRO_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS(ID_PRODUCTO) ON DELETE CASCADE,
  CONSTRAINT CK_RETRO_CONDICION CHECK (CONDICION_ESTETICA_10 BETWEEN 1 AND 10),
  CONSTRAINT CK_RETRO_CAJA CHECK (INCLUYE_CAJA IN ('S','N')),
  CONSTRAINT CK_RETRO_MANUAL CHECK (INCLUYE_MANUAL IN ('S','N')),
  CONSTRAINT CK_RETRO_RECAP CHECK (RECAP_REALIZADO IN ('S','N'))
);

