CREATE INDEX IX_CERTIFICADOS_CODIGO ON CERTIFICADOS_GS(CODIGO_CERTIFICADO);
CREATE INDEX IX_VENTAS_FECHA ON VENTAS(FECHA_VENTA);
CREATE INDEX IX_COMPRAS_FECHA ON COMPRAS(FECHA_COMPRA);
CREATE INDEX IX_DETVENTA_PRODUCTO ON VENTAS_DETALLE(ID_PRODUCTO);
CREATE INDEX IX_DETCOMPRA_PRODUCTO ON COMPRAS_DETALLE(ID_PRODUCTO);
