-- 10. GALERÍA DE FOTOS DE PRODUCTOS
CREATE TABLE PRODUCTOS_FOTOS (
  ID_FOTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_PRODUCTO NUMBER NOT NULL,
  URL_FOTO VARCHAR2(500) NOT NULL,
  ES_PRINCIPAL CHAR(1) DEFAULT 'N' NOT NULL,
  FECHA_CARGA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_PRODUCTOS_FOTOS PRIMARY KEY (ID_FOTO),
  CONSTRAINT FK_FOTO_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS(ID_PRODUCTO) ON DELETE CASCADE,
