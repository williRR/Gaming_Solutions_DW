CREATE TABLE PROVEEDORES (
  ID_PROVEEDOR NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(150) NOT NULL,
  TIPO_PROVEEDOR VARCHAR2(20) DEFAULT 'PARTICULAR' NOT NULL,
  TELEFONO VARCHAR2(20), EMAIL VARCHAR2(100), DIRECCION VARCHAR2(200),
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_PROVEEDORES PRIMARY KEY (ID_PROVEEDOR),
  CONSTRAINT CK_PROVEEDORES_TIPO CHECK (TIPO_PROVEEDOR IN ('EMPRESA','PARTICULAR'))
);

CREATE TABLE CLIENTES (
  ID_CLIENTE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(150) NOT NULL, TELEFONO VARCHAR2(20), EMAIL VARCHAR2(100), DIRECCION VARCHAR2(200),
  FECHA_REGISTRO DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTE)
);

CREATE TABLE CONSOLAS (
  ID_CONSOLA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(150) NOT NULL, MARCA VARCHAR2(80), MODELO VARCHAR2(80),
  TIPO VARCHAR2(10) NOT NULL, PRECIO_VENTA NUMBER(10,2) NOT NULL, PRECIO_COMPRA NUMBER(10,2),
  STOCK NUMBER(6) DEFAULT 0 NOT NULL, DESCRIPCION CLOB, ID_PROVEEDOR NUMBER,
  FECHA_INGRESO DATE DEFAULT SYSDATE NOT NULL, ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_CONSOLAS PRIMARY KEY (ID_CONSOLA),
  CONSTRAINT FK_CONSOLA_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR) REFERENCES PROVEEDORES(ID_PROVEEDOR),
  CONSTRAINT CK_CONSOLAS_TIPO CHECK (TIPO IN ('NUEVA','RETRO')),
  CONSTRAINT CK_CONSOLAS_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CONSTRAINT CK_CONSOLAS_STOCK CHECK (STOCK >= 0),
  CONSTRAINT CK_CONSOLAS_PRECIO CHECK (PRECIO_VENTA >= 0)
);

CREATE TABLE CONSOLAS_RETRO_DETALLE (
  ID_CONSOLA NUMBER NOT NULL, CONDICION_ESTETICA NUMBER(2) NOT NULL,
  INCLUYE_CAJA CHAR(1) DEFAULT 'N' NOT NULL, INCLUYE_MANUAL CHAR(1) DEFAULT 'N' NOT NULL,
  ESTADO_FUNCIONAL VARCHAR2(30) DEFAULT 'FUNCIONAL' NOT NULL, OBSERVACIONES VARCHAR2(1000),
  CONSTRAINT PK_CONSOLAS_RETRO PRIMARY KEY (ID_CONSOLA),
  CONSTRAINT FK_RETRO_CONSOLA FOREIGN KEY (ID_CONSOLA) REFERENCES CONSOLAS(ID_CONSOLA) ON DELETE CASCADE,
  CONSTRAINT CK_RETRO_CONDICION CHECK (CONDICION_ESTETICA BETWEEN 1 AND 10),
  CONSTRAINT CK_RETRO_CAJA CHECK (INCLUYE_CAJA IN ('S','N')),
  CONSTRAINT CK_RETRO_MANUAL CHECK (INCLUYE_MANUAL IN ('S','N')),
  CONSTRAINT CK_RETRO_ESTADO CHECK (ESTADO_FUNCIONAL IN ('FUNCIONAL','PARA REPARAR','NO FUNCIONA'))
);

CREATE TABLE CONSOLAS_FOTOS (
  ID_FOTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_CONSOLA NUMBER NOT NULL, URL_FOTO VARCHAR2(500) NOT NULL,
  ES_PRINCIPAL CHAR(1) DEFAULT 'N' NOT NULL, FECHA_CARGA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_CONSOLAS_FOTOS PRIMARY KEY (ID_FOTO),
  CONSTRAINT FK_FOTO_CONSOLA FOREIGN KEY (ID_CONSOLA) REFERENCES CONSOLAS(ID_CONSOLA) ON DELETE CASCADE,
  CONSTRAINT CK_FOTOS_PRINCIPAL CHECK (ES_PRINCIPAL IN ('S','N'))
);

CREATE TABLE COMPRAS (
  ID_COMPRA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY, ID_PROVEEDOR NUMBER NOT NULL,
  FECHA_COMPRA DATE DEFAULT SYSDATE NOT NULL, TOTAL_COMPRA NUMBER(10,2) DEFAULT 0 NOT NULL,
  OBSERVACIONES VARCHAR2(1000), USUARIO_REGISTRO VARCHAR2(50) DEFAULT USER NOT NULL,
  CONSTRAINT PK_COMPRAS PRIMARY KEY (ID_COMPRA), CONSTRAINT FK_COMPRA_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR) REFERENCES PROVEEDORES(ID_PROVEEDOR),
  CONSTRAINT CK_COMPRAS_TOTAL CHECK (TOTAL_COMPRA >= 0)
);

CREATE TABLE COMPRAS_DETALLE (
  ID_DETALLE_COMPRA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY, ID_COMPRA NUMBER NOT NULL, ID_CONSOLA NUMBER NOT NULL,
  CANTIDAD NUMBER(5) DEFAULT 1 NOT NULL, PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
  SUBTOTAL NUMBER(10,2) GENERATED ALWAYS AS (CANTIDAD * PRECIO_UNITARIO) VIRTUAL,
  CONSTRAINT PK_COMPRAS_DETALLE PRIMARY KEY (ID_DETALLE_COMPRA), CONSTRAINT FK_DETCOMPRA_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES COMPRAS(ID_COMPRA) ON DELETE CASCADE,
  CONSTRAINT FK_DETCOMPRA_CONSOLA FOREIGN KEY (ID_CONSOLA) REFERENCES CONSOLAS(ID_CONSOLA), CONSTRAINT CK_DETCOMPRA_CANTIDAD CHECK (CANTIDAD > 0)
);

CREATE TABLE VENTAS (
  ID_VENTA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY, ID_CLIENTE NUMBER NOT NULL,
  FECHA_VENTA DATE DEFAULT SYSDATE NOT NULL, METODO_PAGO VARCHAR2(20) NOT NULL,
  TOTAL_VENTA NUMBER(10,2) DEFAULT 0 NOT NULL, ESTADO_VENTA VARCHAR2(20) DEFAULT 'COMPLETADA' NOT NULL,
  USUARIO_REGISTRO VARCHAR2(50) DEFAULT USER NOT NULL,
  CONSTRAINT PK_VENTAS PRIMARY KEY (ID_VENTA), CONSTRAINT FK_VENTA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID_CLIENTE),
  CONSTRAINT CK_VENTAS_METODO CHECK (METODO_PAGO IN ('EFECTIVO','TARJETA','TRANSFERENCIA','OTRO')),
  CONSTRAINT CK_VENTAS_ESTADO CHECK (ESTADO_VENTA IN ('COMPLETADA','ANULADA','PENDIENTE')), CONSTRAINT CK_VENTAS_TOTAL CHECK (TOTAL_VENTA >= 0)
);

CREATE TABLE VENTAS_DETALLE (
  ID_DETALLE_VENTA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY, ID_VENTA NUMBER NOT NULL, ID_CONSOLA NUMBER NOT NULL,
  CANTIDAD NUMBER(5) DEFAULT 1 NOT NULL, PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
  SUBTOTAL NUMBER(10,2) GENERATED ALWAYS AS (CANTIDAD * PRECIO_UNITARIO) VIRTUAL,
  CONSTRAINT PK_VENTAS_DETALLE PRIMARY KEY (ID_DETALLE_VENTA), CONSTRAINT FK_DETVENTA_VENTA FOREIGN KEY (ID_VENTA) REFERENCES VENTAS(ID_VENTA) ON DELETE CASCADE,
  CONSTRAINT FK_DETVENTA_CONSOLA FOREIGN KEY (ID_CONSOLA) REFERENCES CONSOLAS(ID_CONSOLA), CONSTRAINT CK_DETVENTA_CANTIDAD CHECK (CANTIDAD > 0)
);

CREATE INDEX IX_CONSOLAS_TIPO ON CONSOLAS(TIPO);
CREATE INDEX IX_CONSOLAS_NOMBRE ON CONSOLAS(NOMBRE);
CREATE INDEX IX_VENTAS_FECHA ON VENTAS(FECHA_VENTA);
CREATE INDEX IX_COMPRAS_FECHA ON COMPRAS(FECHA_COMPRA);
CREATE INDEX IX_DETVENTA_CONSOLA ON VENTAS_DETALLE(ID_CONSOLA);
CREATE INDEX IX_DETCOMPRA_CONSOLA ON COMPRAS_DETALLE(ID_CONSOLA);
