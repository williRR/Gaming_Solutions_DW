-- 11. TABLA DE COMPRAS A PROVEEDORES
CREATE TABLE COMPRAS (
  ID_COMPRA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_PROVEEDOR NUMBER NOT NULL,
  FECHA_COMPRA DATE DEFAULT SYSDATE NOT NULL,
  TOTAL_COMPRA NUMBER(10,2) DEFAULT 0 NOT NULL,
  OBSERVACIONES VARCHAR2(1000),
  USUARIO_REGISTRO VARCHAR2(50) DEFAULT USER NOT NULL,
  CONSTRAINT PK_COMPRAS PRIMARY KEY (ID_COMPRA),
  CONSTRAINT FK_COMPRA_PROVEEDOR FOREIGN KEY (ID_PROVEEDOR) REFERENCES PROVEEDORES(ID_PROVEEDOR),
  CONSTRAINT CK_COMPRAS_TOTAL CHECK (TOTAL_COMPRA >= 0)
);

-- 12. DETALLE DE COMPRAS
CREATE TABLE COMPRAS_DETALLE (
  ID_DETALLE_COMPRA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_COMPRA NUMBER NOT NULL,
  ID_PRODUCTO NUMBER NOT NULL,
  CANTIDAD NUMBER(5) DEFAULT 1 NOT NULL,
  PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
  SUBTOTAL NUMBER(10,2) GENERATED ALWAYS AS (CANTIDAD * PRECIO_UNITARIO) VIRTUAL,
  CONSTRAINT PK_COMPRAS_DETALLE PRIMARY KEY (ID_DETALLE_COMPRA),
  CONSTRAINT FK_DETCOMPRA_COMPRA FOREIGN KEY (ID_COMPRA) REFERENCES COMPRAS(ID_COMPRA) ON DELETE CASCADE,
  CONSTRAINT FK_DETCOMPRA_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS(ID_PRODUCTO),
  CONSTRAINT CK_DETCOMPRA_CANTIDAD CHECK (CANTIDAD > 0)
);

-- 13. TABLA DE VENTAS (OPERACIÓN MANUAL EN EFECTIVO / TRANSFERENCIA)
CREATE TABLE VENTAS (
  ID_VENTA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_CLIENTE NUMBER NOT NULL,
  FECHA_VENTA DATE DEFAULT SYSDATE NOT NULL,
  METODO_PAGO VARCHAR2(20) DEFAULT 'EFECTIVO' NOT NULL,
  TOTAL_VENTA NUMBER(10,2) DEFAULT 0 NOT NULL,
  ESTADO_VENTA VARCHAR2(20) DEFAULT 'COMPLETADA' NOT NULL,
  USUARIO_REGISTRO VARCHAR2(50) DEFAULT USER NOT NULL,
  NOTAS_VENTA VARCHAR2(500),
  CONSTRAINT PK_VENTAS PRIMARY KEY (ID_VENTA),
  CONSTRAINT FK_VENTA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTES(ID_CLIENTE),
  CONSTRAINT CK_VENTAS_METODO CHECK (METODO_PAGO IN ('EFECTIVO','TRANSFERENCIA','TARJETA','OTRO')),
  CONSTRAINT CK_VENTAS_ESTADO CHECK (ESTADO_VENTA IN ('COMPLETADA','ANULADA','PENDIENTE')),
  CONSTRAINT CK_VENTAS_TOTAL CHECK (TOTAL_VENTA >= 0)
);

-- 14. DETALLE DE VENTAS
CREATE TABLE VENTAS_DETALLE (
  ID_DETALLE_VENTA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_VENTA NUMBER NOT NULL,
  ID_PRODUCTO NUMBER NOT NULL,
  CANTIDAD NUMBER(5) DEFAULT 1 NOT NULL,
  PRECIO_UNITARIO NUMBER(10,2) NOT NULL,
  SUBTOTAL NUMBER(10,2) GENERATED ALWAYS AS (CANTIDAD * PRECIO_UNITARIO) VIRTUAL,
  CONSTRAINT PK_VENTAS_DETALLE PRIMARY KEY (ID_DETALLE_VENTA),
  CONSTRAINT FK_DETVENTA_VENTA FOREIGN KEY (ID_VENTA) REFERENCES VENTAS(ID_VENTA) ON DELETE CASCADE,
  CONSTRAINT FK_DETVENTA_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTOS(ID_PRODUCTO),
  CONSTRAINT CK_DETVENTA_CANTIDAD CHECK (CANTIDAD > 0)
);

-- 15. CUPONES DE DESCUENTO Y PROMOCIONES
CREATE TABLE CUPONES_DESCUENTO (
  ID_CUPON NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  CODIGO VARCHAR2(30) NOT NULL,
  PORCENTAJE_DESCUENTO NUMBER(5,2) DEFAULT 0,
