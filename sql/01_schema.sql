-- VISTA DE COMPATIBILIDAD CON LEGACY "CONSOLAS"
CREATE OR REPLACE VIEW CONSOLAS AS
SELECT 
  p.ID_PRODUCTO AS ID_CONSOLA,
  p.NOMBRE,
  p.MARCA,
  p.MODELO,
  CASE WHEN p.TIPO_HARDWARE = 'RETRO' THEN 'RETRO' ELSE 'NUEVA' END AS TIPO,
  p.PRECIO_VENTA,
  p.PRECIO_COMPRA,
  p.STOCK,
  p.DESCRIPCION,
  p.ID_PROVEEDOR,
  p.FECHA_INGRESO,
  p.ACTIVO
FROM PRODUCTOS p;

