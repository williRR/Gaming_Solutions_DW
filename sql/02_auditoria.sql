-- Bitácora centralizada para inventario y ventas.
CREATE TABLE BITACORA_AUDITORIA (
  ID_AUDITORIA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  TABLA_AFECTADA VARCHAR2(30) NOT NULL, ID_REGISTRO NUMBER,
  OPERACION CHAR(1) NOT NULL, USUARIO_BD VARCHAR2(128) DEFAULT USER NOT NULL,
  FECHA_EVENTO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  VALORES_ANTERIORES CLOB, VALORES_NUEVOS CLOB,
  CONSTRAINT PK_BITACORA_AUDITORIA PRIMARY KEY (ID_AUDITORIA),
  CONSTRAINT CK_BITACORA_OPERACION CHECK (OPERACION IN ('I','U','D'))
);

CREATE OR REPLACE TRIGGER TRG_AUD_CONSOLAS
AFTER INSERT OR UPDATE OR DELETE ON CONSOLAS
FOR EACH ROW
BEGIN
  INSERT INTO BITACORA_AUDITORIA (TABLA_AFECTADA, ID_REGISTRO, OPERACION, VALORES_ANTERIORES, VALORES_NUEVOS)
  VALUES ('CONSOLAS', NVL(:NEW.ID_CONSOLA, :OLD.ID_CONSOLA),
    CASE WHEN INSERTING THEN 'I' WHEN UPDATING THEN 'U' ELSE 'D' END,
    CASE WHEN UPDATING OR DELETING THEN JSON_OBJECT('NOMBRE' VALUE :OLD.NOMBRE, 'STOCK' VALUE :OLD.STOCK, 'PRECIO_VENTA' VALUE :OLD.PRECIO_VENTA, 'ACTIVO' VALUE :OLD.ACTIVO RETURNING CLOB) END,
    CASE WHEN INSERTING OR UPDATING THEN JSON_OBJECT('NOMBRE' VALUE :NEW.NOMBRE, 'STOCK' VALUE :NEW.STOCK, 'PRECIO_VENTA' VALUE :NEW.PRECIO_VENTA, 'ACTIVO' VALUE :NEW.ACTIVO RETURNING CLOB) END);
END;
/

CREATE OR REPLACE TRIGGER TRG_AUD_VENTAS
AFTER INSERT OR UPDATE OR DELETE ON VENTAS
FOR EACH ROW
BEGIN
  INSERT INTO BITACORA_AUDITORIA (TABLA_AFECTADA, ID_REGISTRO, OPERACION, VALORES_ANTERIORES, VALORES_NUEVOS)
  VALUES ('VENTAS', NVL(:NEW.ID_VENTA, :OLD.ID_VENTA),
    CASE WHEN INSERTING THEN 'I' WHEN UPDATING THEN 'U' ELSE 'D' END,
    CASE WHEN UPDATING OR DELETING THEN JSON_OBJECT('ID_CLIENTE' VALUE :OLD.ID_CLIENTE, 'TOTAL_VENTA' VALUE :OLD.TOTAL_VENTA, 'ESTADO_VENTA' VALUE :OLD.ESTADO_VENTA RETURNING CLOB) END,
    CASE WHEN INSERTING OR UPDATING THEN JSON_OBJECT('ID_CLIENTE' VALUE :NEW.ID_CLIENTE, 'TOTAL_VENTA' VALUE :NEW.TOTAL_VENTA, 'ESTADO_VENTA' VALUE :NEW.ESTADO_VENTA RETURNING CLOB) END);
END;
/
